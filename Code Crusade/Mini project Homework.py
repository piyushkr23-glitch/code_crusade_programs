# Homework 2 - Temperature Converter

# Temperature Converter

celsius = float(input("Celsius: "))

# Convert Celsius to Fahrenheit
fahrenheit = (celsius * 9 / 5) + 32

# Convert Celsius to Kelvin
kelvin = celsius + 273.15

# Check Fahrenheit
fahrenheit_check = fahrenheit > 100

# Increase Celsius by 5 using += operator
celsius += 5

# Results
print("Fahrenheit:", fahrenheit)
print("Kelvin:", kelvin)
print("Fahrenheit > 100:", fahrenheit_check)
print("Updated Celsius:", celsius)

# Data types
print("Data Types:")
print("Celsius:", type(celsius))
print("Fahrenheit:", type(fahrenheit))
print("Kelvin:", type(kelvin))

